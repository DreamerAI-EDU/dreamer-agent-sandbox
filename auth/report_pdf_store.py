"""PR-6 S2 — on-disk home for the approved-report PDF artifacts.

The state machine stores ``parent_reports.pdf_path`` / ``pdf_sha256``; this
module is the only place that turns those two columns into bytes on disk.

Why a file at all, when the renderer is deterministic? Because the row must
point at *something* that was produced at approval time ("PDF 失敗 = approve
失敗"), and because a parent download should not re-render on every request.
The deterministic bytes give the second half of the guarantee: if the file is
gone (fresh container, cleaned volume), the download path re-renders and
**verifies the hash against the stored one before serving**, so a parent can
never be handed a PDF that differs from the version the teacher approved.

Layout (relative to the repo root, ``var/`` is git-ignored already):

    .pr5_harness/reports_pdf/rpt_<32 hex>.pdf

The directory is overridable with ``DREAMER_REPORT_PDF_DIR`` so a deployment
can mount a volume instead of writing into the image layer.
"""

from __future__ import annotations

import hashlib
import os
import re
from typing import Optional, Tuple

_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

PDF_DIR_ENV = "DREAMER_REPORT_PDF_DIR"
#: 施工令 §S2-4: the harness writes into ``.pr5_harness/reports_pdf/`` (already
#: git-ignored); a deployment mounts its data dir through the env var instead.
DEFAULT_PDF_DIR = os.path.join(".pr5_harness", "reports_pdf")

#: ``report_id`` is generated by report_store as ``rpt_`` + uuid4 hex. Anything
#: else is refused before it touches a path (traversal defence — the id comes
#: from a URL or a DB column, never from a trusted constant).
_REPORT_ID_RE = re.compile(r"^rpt_[0-9a-f]{32}$")


class InvalidReportId(ValueError):
    """The id is not shaped like a report id — never used in a path."""


def pdf_root() -> str:
    """Absolute artifact directory (``$DREAMER_REPORT_PDF_DIR`` or default)."""
    configured = os.environ.get(PDF_DIR_ENV, "")
    if configured:
        return configured if os.path.isabs(configured) else os.path.join(_REPO_ROOT, configured)
    return os.path.join(_REPO_ROOT, DEFAULT_PDF_DIR)


def relative_pdf_path(report_id: str) -> str:
    """Portable, POSIX-separated path stored in ``parent_reports.pdf_path``.

    Relative on purpose: the row survives a container rebuild / volume mount
    change, and the absolute location is derived from config at read time.
    """
    if not _REPORT_ID_RE.match(report_id or ""):
        raise InvalidReportId(report_id)
    configured = os.environ.get(PDF_DIR_ENV, "")
    if configured:
        directory = configured if os.path.isabs(configured) else configured
        return "/".join(
            [directory.replace("\\", "/").rstrip("/"), f"{report_id}.pdf"]
        )
    return "/".join([DEFAULT_PDF_DIR.replace("\\", "/"), f"{report_id}.pdf"])


def absolute_pdf_path(stored_path: str) -> str:
    """Resolve a stored path to an absolute one (never leaves the root)."""
    normalised = (stored_path or "").replace("\\", "/").strip()
    if not normalised:
        raise InvalidReportId(stored_path)
    if os.path.isabs(normalised):
        return normalised
    return os.path.join(_REPO_ROOT, *normalised.split("/"))


def store_pdf(report_id: str, data: bytes) -> Tuple[str, str]:
    """Write the artifact, return ``(stored_path, sha256)``.

    Raises ``OSError`` when the directory is not writable — the approval path
    turns that into a failed approval instead of publishing a report whose
    download would 404 later.
    """
    stored_path = relative_pdf_path(report_id)
    absolute = absolute_pdf_path(stored_path)
    os.makedirs(os.path.dirname(absolute), exist_ok=True)
    tmp_path = absolute + ".tmp"
    with open(tmp_path, "wb") as fh:
        fh.write(data)
    os.replace(tmp_path, absolute)
    return stored_path, sha256_of(data)


def read_pdf(stored_path: str) -> Optional[bytes]:
    """Bytes of a stored artifact, or ``None`` when it is not on disk."""
    try:
        absolute = absolute_pdf_path(stored_path)
    except InvalidReportId:
        return None
    if not os.path.isfile(absolute):
        return None
    with open(absolute, "rb") as fh:
        return fh.read()


def sha256_of(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()
